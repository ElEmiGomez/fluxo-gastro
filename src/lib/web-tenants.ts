/**
 * Resuelve la configuración completa de un local gastronómico por su slug
 */
export async function getGastronomicTenant(slug: string): Promise<GastronomicTenantConfig | null> {
  const normalized = (slug || '').toLowerCase().trim()
  if (SEED_TENANTS[normalized]) {
    return SEED_TENANTS[normalized]
  }

  // Soporte para variantes comunes de slug
  if (normalized.includes('casa-mar') || normalized === 'casamar') {
    return SEED_TENANTS['casa-mar-da-vila']
  }
  if (
    normalized === 'bar-jaratusas' ||
    normalized === 'jaratusas' ||
    normalized === 'jara-tusas' ||
    normalized.includes('jaratusas') ||
    normalized.includes('jara-tusas')
  ) {
    return SEED_TENANTS['bar-jaratusas']
  }

  return null
}
