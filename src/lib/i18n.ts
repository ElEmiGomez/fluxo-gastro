const SUPPORTED_LANG_CODES: SupportedLanguage[] = ['gl', 'es', 'en', 'fr', 'de', 'pt', 'it', 'nl', 'ca', 'eu']

export function resolveLang(lang: string): SupportedLanguage {
  if (SUPPORTED_LANG_CODES.includes(lang as SupportedLanguage)) {
    return lang as SupportedLanguage
  }
  return 'es'
}

export function getTranslation(lang: string, key: string): string {
  const code = resolveLang(lang)
  return TRANSLATIONS[code]?.[key] || TRANSLATIONS.es[key] || TRANSLATIONS.gl[key] || key
}

export function translateCategoryName(lang: string, originalName: string): string {
  const code = resolveLang(lang)
  const upper = (originalName || '').toUpperCase().trim()
  if (upper === 'GIN & BEBIDAS' || upper.includes('GIN & BEBIDAS')) {
    if (code === 'en') return 'Drinks'
    if (code === 'fr') return 'Boissons'
    if (code === 'de') return 'Getränke'
    if (code === 'nl') return 'Dranken'
    if (code === 'eu') return 'Edariak'
    if (code === 'ca') return 'Begudes'
    return 'Bebidas'
  }
  return CATEGORY_TRANSLATIONS[code]?.[upper] || originalName
}

